let n = 0;
function mk(
  sub: SubspecialtyCode,
  difficulty: 1 | 2 | 3 | 4 | 5,
  cognitiveLevel: CognitiveLevel,
  stem: string,
  correct: string,
  wrong: string[],
  explanation: string,
  ref: Reference,
  structure?: string,
  careerLevel: CareerLevel = "both",
): Question {
  n += 1;
  const id = `demo-${sub}-${String(n).padStart(3, "0")}`;
  return {
    id,
    type: "single_choice",
    subspecialty: sub,
    careerLevel,
    difficulty,
    cognitiveLevel,
    structure,
    stem,
    options: [
      { id: `${id}-a`, text: correct, isCorrect: true },
      ...wrong.map((t, i) => ({
        id: `${id}-${String.fromCharCode(98 + i)}`,
        text: t,
        isCorrect: false,
      })),
    ],
    explanation,
    references: [ref],
    status: "pending_review",
    validationLevel: "ai_generated",
    aiAssisted: true,
  };
}

